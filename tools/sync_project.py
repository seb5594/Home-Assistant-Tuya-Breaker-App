"""Render the checked-in Home Assistant build contexts from project.json.

Home Assistant builds every app straight from its own folder, so everything an app needs
has to be committed there: its config.yaml, Dockerfile, translations and a copy of the
code both apps share. Nothing in those files is written by hand. Edit project.json,
templates/ or shared/ and run this script; CI runs it with --check and fails on drift.
"""
import argparse
import json
from pathlib import Path
import re
import sys

import yaml

ROOT = Path(__file__).resolve().parents[1]
HEADER = "# Generated by tools/sync_project.py from project.json; do not edit.\n"


def replaced(text, old, new, count=1):
    """text.replace(old, new), but fail loudly if `old` is not found `count` times.

    A silent no-op here (e.g. because a vendored source changed upstream) would ship a page
    missing a transformation nobody noticed was skipped, instead of a build-time error.
    """
    found = text.count(old)
    assert found == count, f"Expected {count} occurrence(s) of {old!r}, found {found}"
    return text.replace(old, new, count)
# Keys of project.json that the running apps read from build_info.json.
BUILD_INFO_KEYS = ("version", "protocol", "upstream_revision", "upstream_repository")


def render_config(spec, slug, app):
    """config.yaml of one app: shared defaults first, then the app's own settings."""
    config = {"name": app["config"]["name"], "version": spec["version"], "slug": slug,
              **spec["common_config"], **app["config"],
              "options": {**spec["common_options"], **app["options"]},
              "schema": {**spec["common_schema"], **app["schema"]}}
    return config, HEADER + yaml.safe_dump(config, sort_keys=False, allow_unicode=True)


def render_dockerfile(spec, slug, app, root):
    """Fill the placeholders (@@NAME@@) of the app's Dockerfile template."""
    packages = lambda names: " ".join(names)
    values = {"BASE_IMAGE": spec["base_image"], "VERSION": spec["version"],
              "UPSTREAM_REPOSITORY": spec.get("upstream_repository", ""),
              "UPSTREAM_REVISION": spec.get("upstream_revision", ""),
              "BUILD_PACKAGES": packages(spec["build_packages"]),
              "RUNTIME_PACKAGES": packages(app["packages"]),
              "PYTHON_PACKAGES": " ".join(f"{name}=={version}" for name, version in spec.get("python_packages", {}).items())}
    values.update({"CLOUDCUTTER_REPOSITORY": spec.get("cloudcutter_repository", ""),
                   "CLOUDCUTTER_REVISION": spec.get("cloudcutter_revision", "")})
    template = (root / "templates" / f"{slug}.Dockerfile").read_text(encoding="utf-8")
    return HEADER + re.sub(r"@@([A-Z_]+)@@", lambda match: values[match[1]], template)


def render_shared_module(source):
    """A copy of shared/<name>.py with a banner, so nobody edits the copy by mistake."""
    banner = f"# Copy of shared/{source.name}, maintained by tools/sync_project.py. Edit the original.\n"
    return banner + source.read_text(encoding="utf-8")


def outputs(root=ROOT):
    """Every generated file as {relative path: content}."""
    spec = json.loads((root / "project.json").read_text(encoding="utf-8"))
    files = {}
    build_info = {key: spec[key] for key in BUILD_INFO_KEYS if key in spec}
    build_info["repository_url"] = spec["common_config"]["url"]
    for slug, app in spec["apps"].items():
        config, files[f"{slug}/config.yaml"] = render_config(spec, slug, app)
        files[f"{slug}/Dockerfile"] = render_dockerfile(spec, slug, app, root)
        info = dict(build_info)
        if slug == "tuya_breaker":
            info.update(cloudcutter_repository=spec["cloudcutter_repository"],
                        cloudcutter_revision=spec["cloudcutter_revision"],
                        lightleak_repository=spec["lightleak_repository"],
                        lightleak_revision=spec["lightleak_revision"])
        files[f"{slug}/app/build_info.json"] = json.dumps(info, indent=2) + "\n"
        for source in sorted((root / "shared").glob("*.py")):
            files[f"{slug}/app/{source.name}"] = render_shared_module(source)
        sdk = root / ('sdk/wifi_helper' if slug == 'wifi_helper' else 'vendor/wifi_helper')
        for source_name, target_name in (("wifi.py","wifi.py"),("protocol.py","protocol.py"),("client.py","lease.py")):
            source = sdk / source_name
            text = source.read_text(encoding="utf-8").replace('from .wifi import', 'from wifi import').replace('from .protocol import', 'from protocol import')
            files[f"{slug}/app/{target_name}"] = '# Generated from the pinned WiFi Helper SDK; do not edit.\n' + text
        for language, fields in spec["translations"].items():
            translation = {key: fields[key] for key in config["options"]}
            files[f"{slug}/translations/{language}.json"] = json.dumps({"configuration": translation}, indent=2, ensure_ascii=False) + "\n"
    if "tuya_breaker" in spec["apps"]:
        # Share the proven UI, runner, Wi-Fi and HTTP code without maintaining a fork.
        # Breaker-specific source files live alongside these generated base modules.
        for source in (root / "vendor/untuyaos3/app").glob("*.py"):
            if source.name not in {"lease.py", "protocol.py", "wifi.py", "journal.py"}:
                files[f"tuya_breaker/app/{source.name}"] = "# Generated base module from vendor/untuyaos3/app; do not edit.\n" + source.read_text(encoding="utf-8")
        for name in ("app.js", "style.css"):
            files[f"tuya_breaker/app/static/{name}"] = (root / "vendor/untuyaos3/app/static" / name).read_text(encoding="utf-8")
        files['tuya_breaker/app/static/style.css'] += '\n' + (root/'tuya_breaker/ui/style.css').read_text(encoding='utf-8')
        app_js = files["tuya_breaker/app/static/app.js"]
        app_js = replaced(app_js, 'document.querySelector(".terminal-card")', 'document.querySelector("#session-overview")')
        app_js = replaced(app_js, 'Session active. Follow the console; submit a menu choice when prompted.',
                          'Session active. Check session progress for the next step.')
        files["tuya_breaker/app/static/app.js"] = app_js
        files['tuya_breaker/app/static/style.css'] += '\n' + (root/'tuya_breaker/ui/hardware.css').read_text(encoding='utf-8')
        files['tuya_breaker/app/static/style.css'] += '\n' + (root/'tuya_breaker/ui/session.css').read_text(encoding='utf-8')
        page = (root / "vendor/untuyaos3/app/static/index.html").read_text(encoding="utf-8")
        # The vendored source already says "WiFi App Helper" (renamed upstream); nothing to rewrite here.
        page = replaced(page, '<title>UnTuyaOS3</title>', '<title>Tuya Breaker</title>')
        page = replaced(page, '<h1>🔓 UnTuyaOS3<span', '<h1>🔓 Tuya Breaker<span')
        tools_page = (root / 'tuya_breaker/ui/tools.html').read_text(encoding='utf-8')
        tools_page = replaced(tools_page, '<!-- HARDWARE_EXPLORER -->', (root/'tuya_breaker/ui/hardware.html').read_text(encoding='utf-8'))
        page = replaced(page, '<main>', '<main>\n' + tools_page)
        page = replaced(page, '</head>', '<script src="breaker.js" defer></script><script src="lightleak.js" defer></script><script src="hardware.js" defer></script><script src="session.js" defer></script></head>')
        session_page = (root / 'tuya_breaker/ui/session.html').read_text(encoding='utf-8')
        page = replaced(page, '<div class="workspace">', session_page + '<div class="workspace">')
        page = replaced(page,
            '<section class="card terminal-card"><div class="section-heading"><div><span class="eyebrow">🖥️ INTERACTIVE SESSION</span><h2>UnTuyaOS3 console</h2></div><span class="live">● LIVE</span></div>',
            '<section class="card terminal-card"><details id="session-console"><summary>Session console</summary>')
        page = replaced(page,
            '<form id="choice-form">',
            '</details><div id="session-menu" hidden><h3 id="session-menu-title"></h3>'
            '<div id="session-menu-options" role="group" aria-labelledby="session-menu-title"></div></div>'
            '<form id="choice-form">')
        page = replaced(page,
            'Answer the numbered prompts above. Your session continues when you close this page.',
            'Submit the menu choice shown here or open the console for the full prompt.')
        page = replaced(page,
            '<section class="card log-card"><div class="section-heading"><div><span class="eyebrow">📋 ALWAYS VISIBLE</span><h2>Activity & diagnostics</h2></div>',
            '<section class="card log-card"><details id="session-diagnostics"><summary>Activity &amp; diagnostics</summary><div class="section-heading">')
        page = replaced(page, 'Retention is limited to 6 MiB.</p></section>', 'Retention is limited to 6 MiB.</p></details></section>')
        page = replaced(page, '<div class="preparation-body"><p>', '<div class="preparation-body"><p id="preparation-help">')
        page = replaced(page, '<p class="hint">Kickstart starts', '<p id="kickstart-help" class="hint">Kickstart starts')
        page = replaced(page, '<option>T1</option>', '<option>T1</option><option>BK7231T</option><option>RTL8710BN</option>')
        page = replaced(page, 'Give compatible Tuya devices a new beginning.', 'UnTuyaOS3, Lightleak and Tuya-Cloudcutter in Home Assistant.')
        # The vendored footer already carries the developer-credit/support block; nothing to append here.
        files["tuya_breaker/app/static/index.html"] = page
        files["tuya_breaker/integration/patch_upstream.py"] = (root / "vendor/untuyaos3/integration/patch_upstream.py").read_text(encoding="utf-8")
        files["tuya_breaker/integration/dhcp.sh"] = (root / "vendor/untuyaos3/integration/dhcp.sh").read_text(encoding="utf-8")
    files[".github/apps.json"] = json.dumps({"apps": list(spec["apps"])}, indent=2) + "\n"
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if generated files differ; do not modify files")
    options = parser.parse_args()
    changed = []
    for name, text in outputs().items():
        path = ROOT / name
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            changed.append(name)
            if not options.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8", newline="\n")
    if changed:
        print(("Out of date: " if options.check else "Generated: ") + ", ".join(changed))
    if options.check and changed:
        print("Run python tools/sync_project.py after editing project.json, templates/ or shared/.", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
